#!/usr/bin/env bash
# deploy-gateway-canary-operator-role.sh — Create, update or delete the
# OUT-OF-BAND, EPHEMERAL operator role that the Gateway source-condition
# broker's canary lanes assume (scripts/run-gateway-runtime-source-broker.mjs).
#
# The role exists only for a canary window: deploy it, run the broker (and the
# guarded rollout), then remove it with --delete. The check that the owner
# already holds every operator permission runs only here and at broker start.
# A role left in place keeps trusting the owner after the owner has been
# narrowed (for example after losing AdministratorAccess), and so lets it
# regain those permissions.
#
# The role is named gateway-canary-operator-mem9-on-aws, outside the
# mem9-on-aws-* role namespace that the deploy role administers. Only the one
# configured same-account owner role may assume it. That trust names the role,
# so it is equivalent to an UNRESTRICTED session of the owner role: it admits
# every session of it, including one narrowed by a session policy or an IAM
# Identity Center permission set. The owner check below cannot see session
# policies. Never issue a scoped or narrowed owner session that allows
# sts:AssumeRole or sts:TagSession on gateway-canary-operator-mem9-on-aws.
# Its single inline policy
# is the union of the canary's observe, bootstrap and provision lane policies,
# generalized only in the verification-id segment
# (infra/cloudformation/gateway-canary-operator-role.yaml, generated by
# scripts/lib/gateway-canary-operator-role.mjs). It grants no sts:AssumeRole.
#
# The role is ADMINISTRATOR-EQUIVALENT: CreateStack takes an arbitrary template,
# so its CloudFormation, IAM and Lambda grants can create any policy and role.
# It must grant the owner nothing new. Before any stack call this script
# therefore reads the owner role's own identity policies and permissions
# boundary and simulates them (iam simulate-custom-policy) beside the
# operator's own policy on the same cases, refusing unless every pair the
# operator is allowed is allowed to the owner. It also refuses the operator
# itself and any CI-reachable role (by path, name or CI role glob) as the owner.
#
# SCPs and RCPs are excluded from that simulation (SimulatePrincipalPolicy's
# Organizations evaluation denies actions the principal performs). That is
# sound only if no SCP or RCP treats the owner differently from the operator,
# i.e. none conditions on any aws:Principal* key, aws:userid or
# aws:SourceIdentity. The operator states this explicitly:
#   GATEWAY_CANARY_ORG_POLICIES_PRINCIPAL_NEUTRAL=true
# Without it the script refuses. Where Organizations policies for the account
# and its OU chain are readable, they are also scanned for those keys, and any
# match refuses even with the acknowledgement.
#
# Deploy for each canary window, and delete afterwards. The stack is hosted in
# us-west-2 with the other account-global IAM ownership stacks, and its
# DeletionPolicy is Delete. --delete also removes a role left behind by an
# older Retain stack: it first updates such a stack to the current template, or,
# failing that, deletes the inline policy and then the role directly. It ends
# by verifying that iam get-role reports NoSuchEntity.
#
# Usage:
#   GATEWAY_CANARY_ORG_POLICIES_PRINCIPAL_NEUTRAL=true \
#   GATEWAY_CANARY_OWNER_ROLE_ARN=arn:aws:iam::<account>:role/<owner-role> \
#     [CC_PROJECT=<project> CC_USAGE=cc-<project>] \
#     scripts/deploy-gateway-canary-operator-role.sh
#   scripts/deploy-gateway-canary-operator-role.sh --delete
#
# With CC_PROJECT and CC_USAGE set, the trust also allows sts:TagSession and
# requires exactly those Project and usage session tags. The broker passes the
# same tags from the same variables, and refuses to start if they differ.

set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
if [[ "${1:-}" == "--help" || "${1:-}" == "-h" ]]; then
  sed -n '2,/^$/p' "$0" | sed 's/^# \?//'
  exit 0
fi
MODE=deploy
if [[ "${1:-}" == "--delete" && $# -eq 1 ]]; then
  MODE=delete
elif [[ $# -ne 0 ]]; then
  echo "unsupported operator-role deployment argument" >&2
  exit 2
fi
# shellcheck source=/dev/null
if [[ -f "$ROOT/.env" && "${GATEWAY_CANARY_SKIP_DOTENV:-false}" != "true" ]]; then
  set -a
  . "$ROOT/.env"
  set +a
fi

STACK_REGION="us-west-2"
STACK_NAME="gateway-canary-operator-mem9-on-aws"
TEMPLATE="$ROOT/infra/cloudformation/gateway-canary-operator-role.yaml"
OWNER_ROLE_ARN="${GATEWAY_CANARY_OWNER_ROLE_ARN:-}"
OPERATOR_ROLE_NAME="gateway-canary-operator-mem9-on-aws"

# --delete: remove the stack and the role, and prove the role is gone.
if [[ "$MODE" == "delete" ]]; then
  set +e
  DESCRIPTION=$(aws cloudformation describe-stacks --stack-name "$STACK_NAME" --region "$STACK_REGION" --output json 2>&1)
  DESCRIBE_STATUS=$?
  set -e
  if [[ $DESCRIBE_STATUS -eq 0 ]]; then
    if ! ORIGINAL=$(aws cloudformation get-template --stack-name "$STACK_NAME" --region "$STACK_REGION" \
      --template-stage Original --query TemplateBody --output text); then
      echo "Could not read the operator role stack template." >&2
      exit 1
    fi
    if grep -Eq 'DeletionPolicy:[[:space:]]*"?Retain' <<<"$ORIGINAL"; then
      # An older stack retains the role on deletion; move it to the Delete template first.
      if node "$ROOT/scripts/gateway-canary-operator-owner.mjs" check-template "$TEMPLATE" &&
        aws cloudformation update-stack --stack-name "$STACK_NAME" --region "$STACK_REGION" \
          --template-body "file://${TEMPLATE}" --capabilities CAPABILITY_NAMED_IAM \
          --parameters ParameterKey=OwnerRoleName,UsePreviousValue=true ParameterKey=ApplicationRegion,UsePreviousValue=true \
            ParameterKey=SessionTagProject,UsePreviousValue=true ParameterKey=SessionTagUsage,UsePreviousValue=true >/dev/null &&
        aws cloudformation wait stack-update-complete --stack-name "$STACK_NAME" --region "$STACK_REGION"; then
        echo "operator role stack moved to DeletionPolicy Delete"
      else
        echo "Could not move the stack to DeletionPolicy Delete; the retained role will be deleted directly." >&2
      fi
    fi
    aws cloudformation delete-stack --stack-name "$STACK_NAME" --region "$STACK_REGION"
    if ! aws cloudformation wait stack-delete-complete --stack-name "$STACK_NAME" --region "$STACK_REGION"; then
      echo "Operator role stack deletion did not complete." >&2
      exit 1
    fi
  elif ! grep -Eq 'ValidationError.*does not exist' <<<"$DESCRIPTION"; then
    printf '%s\n' "$DESCRIPTION" >&2
    exit "$DESCRIBE_STATUS"
  fi
  # A role that outlived its stack (Retain) is removed directly: inline policy, then role.
  set +e
  ROLE=$(aws iam get-role --role-name "$OPERATOR_ROLE_NAME" --query Role.RoleName --output text 2>&1)
  ROLE_STATUS=$?
  set -e
  if [[ $ROLE_STATUS -eq 0 ]]; then
    ATTACHED=$(aws iam list-attached-role-policies --role-name "$OPERATOR_ROLE_NAME" --query 'length(AttachedPolicies)' --output text)
    if [[ "$ATTACHED" != "0" ]]; then
      echo "The operator role has attached managed policies; refusing to guess. Detach them, then rerun --delete." >&2
      exit 1
    fi
    INLINE=$(aws iam list-role-policies --role-name "$OPERATOR_ROLE_NAME" --query 'PolicyNames' --output text)
    for policy in $INLINE; do
      aws iam delete-role-policy --role-name "$OPERATOR_ROLE_NAME" --policy-name "$policy"
    done
    aws iam delete-role --role-name "$OPERATOR_ROLE_NAME"
  elif ! grep -q 'NoSuchEntity' <<<"$ROLE"; then
    printf '%s\n' "$ROLE" >&2
    exit "$ROLE_STATUS"
  fi
  set +e
  ROLE=$(aws iam get-role --role-name "$OPERATOR_ROLE_NAME" --query Role.RoleName --output text 2>&1)
  ROLE_STATUS=$?
  set -e
  if [[ $ROLE_STATUS -eq 0 ]] || ! grep -q 'NoSuchEntity' <<<"$ROLE"; then
    echo "The operator role still exists or could not be confirmed absent." >&2
    exit 1
  fi
  echo "gateway canary operator role: deleted"
  exit 0
fi

if [[ "${GATEWAY_CANARY_ORG_POLICIES_PRINCIPAL_NEUTRAL:-}" != "true" ]]; then
  echo "Set GATEWAY_CANARY_ORG_POLICIES_PRINCIPAL_NEUTRAL=true only if no SCP or RCP conditions on any aws:Principal* key, aws:userid or aws:SourceIdentity." >&2
  exit 2
fi

if [[ ! "$OWNER_ROLE_ARN" =~ ^arn:aws:iam::([0-9]{12}):role/([A-Za-z0-9_+=,.@/-]{1,512})$ ]]; then
  echo "GATEWAY_CANARY_OWNER_ROLE_ARN must be an exact IAM role ARN" >&2
  exit 2
fi
OWNER_ACCOUNT="${BASH_REMATCH[1]}"
OWNER_ROLE_PATH_AND_NAME="${BASH_REMATCH[2]}"
OWNER_ROLE_NAME="${OWNER_ROLE_PATH_AND_NAME##*/}"
if ! node "$ROOT/scripts/gateway-canary-operator-owner.mjs" check-owner "$OWNER_ROLE_ARN"; then
  echo "The operator role, mem9-on-a* project roles and github-actions-mem9-on-aws* deploy roles cannot own the canary operator." >&2
  exit 2
fi

# The same validation the broker applies to its session tags.
if ! TAGS=$(cd "$ROOT" && node --input-type=module -e '
  const {gatewaySourceBrokerSessionTags}=await import("./scripts/lib/gateway-runtime-source-broker.mjs");
  const tags=gatewaySourceBrokerSessionTags(process.env)?.tags;
  process.stdout.write(tags?tags.map(t=>t.Value).join(" "):"");' 2>/dev/null); then
  echo "CC_PROJECT and CC_USAGE must both be unset, or both set with CC_USAGE=cc-<project> or codex-<project>" >&2
  exit 2
fi
SESSION_TAG_PROJECT="${TAGS%% *}"
SESSION_TAG_USAGE="${TAGS#* }"
if [[ -z "$TAGS" ]]; then
  SESSION_TAG_PROJECT=""
  SESSION_TAG_USAGE=""
fi

APPLICATION_REGION=$(node "$ROOT/scripts/resolve-application-region.mjs")
CALLER_ACCOUNT=$(aws sts get-caller-identity --query Account --output text)
if [[ "$CALLER_ACCOUNT" != "$OWNER_ACCOUNT" ]]; then
  echo "The owner role must be in the caller's account; refusing a cross-account trust." >&2
  exit 2
fi
LIVE_OWNER_ARN=$(aws iam get-role --role-name "$OWNER_ROLE_NAME" --query Role.Arn --output text)
if [[ "$LIVE_OWNER_ARN" != "$OWNER_ROLE_ARN" ]]; then
  echo "The owner role ARN does not match the existing role." >&2
  exit 1
fi

# The owner must already hold every operator permission.
if ! node "$ROOT/scripts/gateway-canary-operator-owner.mjs" verify-owner "$OWNER_ACCOUNT" "$APPLICATION_REGION" "$OWNER_ROLE_ARN"; then
  echo "The owner role's own policies do not allow every operator permission; the operator would grant it new privileges." >&2
  exit 1
fi

# The committed template must be exactly what the lane-policy compiler renders.
if ! node "$ROOT/scripts/gateway-canary-operator-owner.mjs" check-template "$TEMPLATE"; then
  echo "Operator role template is not the compiler output; no stack call attempted." >&2
  exit 1
fi

if ! aws cloudformation validate-template \
  --template-body "file://${TEMPLATE}" \
  --region "$STACK_REGION" >/dev/null; then
  echo "Operator role template validation failed; no stack mutation attempted." >&2
  exit 1
fi

PARAMETERS=(
  "ParameterKey=OwnerRoleName,ParameterValue=${OWNER_ROLE_PATH_AND_NAME}"
  "ParameterKey=ApplicationRegion,ParameterValue=${APPLICATION_REGION}"
  "ParameterKey=SessionTagProject,ParameterValue=${SESSION_TAG_PROJECT}"
  "ParameterKey=SessionTagUsage,ParameterValue=${SESSION_TAG_USAGE}"
)

stack_parameter() {
  jq -er --arg key "$2" '[.Stacks[0].Parameters[]? | select(.ParameterKey == $key) | .ParameterValue]
    | if length == 1 then .[0] else error("parameter") end' <<<"$1"
}
stack_stable() {
  jq -e '(.Stacks | length) == 1 and (.Stacks[0].StackStatus | test("^(CREATE|UPDATE)_COMPLETE$"))' <<<"$1" >/dev/null
}

set +e
DESCRIPTION=$(aws cloudformation describe-stacks --stack-name "$STACK_NAME" --region "$STACK_REGION" --output json 2>&1)
DESCRIBE_STATUS=$?
set -e
if [[ $DESCRIBE_STATUS -ne 0 ]]; then
  if ! grep -Eq 'ValidationError.*does not exist' <<<"$DESCRIPTION"; then
    printf '%s\n' "$DESCRIPTION" >&2
    exit "$DESCRIBE_STATUS"
  fi
  aws cloudformation create-stack \
    --stack-name "$STACK_NAME" \
    --template-body "file://${TEMPLATE}" \
    --parameters "${PARAMETERS[@]}" \
    --capabilities CAPABILITY_NAMED_IAM \
    --region "$STACK_REGION" \
    --tags Key=Project,Value=mem9-on-aws Key=ManagedBy,Value=cli >/dev/null
  aws cloudformation wait stack-create-complete --stack-name "$STACK_NAME" --region "$STACK_REGION"
else
  if ! stack_stable "$DESCRIPTION"; then
    echo "Existing operator role stack is not in a stable state." >&2
    exit 1
  fi
  EXISTING_REGION=$(stack_parameter "$DESCRIPTION" ApplicationRegion) || exit 1
  if [[ "$EXISTING_REGION" != "$APPLICATION_REGION" ]]; then
    echo "Existing operator role stack belongs to application region ${EXISTING_REGION}; refusing to retarget it to ${APPLICATION_REGION}." >&2
    exit 1
  fi
  set +e
  OUTPUT=$(aws cloudformation update-stack \
    --stack-name "$STACK_NAME" \
    --template-body "file://${TEMPLATE}" \
    --parameters "${PARAMETERS[@]}" \
    --capabilities CAPABILITY_NAMED_IAM \
    --region "$STACK_REGION" 2>&1)
  STATUS=$?
  set -e
  if [[ $STATUS -ne 0 ]]; then
    if grep -q "No updates are to be performed" <<<"$OUTPUT"; then
      echo "gateway canary operator role: no changes"
    else
      printf '%s\n' "$OUTPUT" >&2
      exit "$STATUS"
    fi
  else
    aws cloudformation wait stack-update-complete --stack-name "$STACK_NAME" --region "$STACK_REGION"
  fi
fi

DESCRIPTION=$(aws cloudformation describe-stacks --stack-name "$STACK_NAME" --region "$STACK_REGION" --output json)
if ! stack_stable "$DESCRIPTION" ||
  [[ "$(stack_parameter "$DESCRIPTION" OwnerRoleName)" != "$OWNER_ROLE_PATH_AND_NAME" ||
     "$(stack_parameter "$DESCRIPTION" ApplicationRegion)" != "$APPLICATION_REGION" ||
     "$(stack_parameter "$DESCRIPTION" SessionTagProject)" != "$SESSION_TAG_PROJECT" ||
     "$(stack_parameter "$DESCRIPTION" SessionTagUsage)" != "$SESSION_TAG_USAGE" ]]; then
  echo "Final operator role stack does not match the requested owner, region and tags." >&2
  exit 1
fi
echo "gateway canary operator role: ready ($(jq -r '.Stacks[0].Outputs[]? | select(.OutputKey == "RoleArn") | .OutputValue' <<<"$DESCRIPTION"))"
