/** Package application-owned schemas independently of the IaC tool's SDK. */
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {builtinModules} from 'node:module';
import {join,relative} from 'node:path';
import {fileURLToPath} from 'node:url';
import {rolldown,VERSION,RUNTIME_MODULE_ID} from 'rolldown';
import {parse} from '@babel/parser';
import traverseModule from '@babel/traverse';

const root=fileURLToPath(new URL('..',import.meta.url)),entry='scripts/lib/production-nonroot-observer-sdk-source.mjs';
const outputPath='scripts/lib/production-nonroot-observer-sdk.mjs',manifestPath='scripts/lib/production-nonroot-observer-sdk.json';
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const need=(ok,code)=>{if(!ok)throw Error(code);};
const traverse=traverseModule.default??traverseModule;

export function isolateObserverSdkCode(code){
 const ast=parse(code,{sourceType:'module'}),edits=[],imports=[],exports=[];
 for(const node of ast.program.body){
  if(node.type==='ImportDeclaration'){imports.push(code.slice(node.start,node.end));edits.push([node.start,node.end,'']);}
  if(node.type==='ExportNamedDeclaration'){
   need(!node.source&&!node.declaration&&node.specifiers.every(s=>s.type==='ExportSpecifier'&&s.local.type==='Identifier'&&s.exported.type==='Identifier'&&s.local.name===s.exported.name),'ObserverSdkExports');
   exports.push(...node.specifiers.map(s=>s.local.name));edits.push([node.start,node.end,'']);
  }
  need(!['ExportDefaultDeclaration','ExportAllDeclaration'].includes(node.type),'ObserverSdkExports');
 }
 need(exports.sort().join()==='decodeObserverSdkResponse,hasObserverSdkAction','ObserverSdkExports');
 // The surrounding action's verified region loader owns its compiler helper.
 // Rename only this artifact's private binding, never strings or SDK classes.
 traverse(ast,{Program(path){
  const binding=path.scope.getBinding('__esmMin');
  if(binding){
   need(binding.constant&&binding.path.isVariableDeclarator(),'ObserverSdkRuntimeBinding');
   for(const node of [binding.identifier,...binding.referencePaths.map(p=>p.node)]){
    need(node.type==='Identifier'&&node.name==='__esmMin','ObserverSdkRuntimeBinding');
    edits.push([node.start,node.end,'__observerSdkEsm']);
   }
  }
  path.stop();
 }});
 for(const [start,end,value]of edits.sort((a,b)=>b[0]-a[0]))code=code.slice(0,start)+value+code.slice(end);
 // Keep original SDK class bindings in their own lexical scope when a second
 // bundler also includes the SDK. No runtime class-name mutation is needed.
 return imports.join('\n')+'\nconst __observerSdk = (() => {\n'+code+'\nreturn {hasObserverSdkAction,decodeObserverSdkResponse};\n})();\n'+
  'export const hasObserverSdkAction = __observerSdk.hasObserverSdkAction;\nexport const decodeObserverSdkResponse = __observerSdk.decodeObserverSdkResponse;\n';
}

export async function buildObserverSdkCodec({check=false}={}){
 const lockBytes=await readFile(join(root,'package-lock.json')),lock=JSON.parse(lockBytes);
 const bundler=lock.packages['node_modules/rolldown'];
 need(bundler?.version===VERSION&&typeof bundler.integrity==='string','ObserverSdkBundlerLock');
 const warnings=[],bundle=await rolldown({cwd:root,input:join(root,entry),platform:'node',resolve:{mainFields:['module','main']},onwarn:warning=>warnings.push(warning)});
 let result;
 try{result=await bundle.generate({format:'esm',codeSplitting:false,keepNames:true,
  banner:'// Generated by scripts/build-observer-sdk-codec.mjs from scripts/lib/production-nonroot-observer-sdk-source.mjs.'});}
 finally{await bundle.close();}
 need(warnings.length===0&&result.output.length===1&&result.output[0].type==='chunk','ObserverSdkBundleOutput');
 const chunk=result.output[0],builtins=new Set(builtinModules.flatMap(name=>[name,'node:'+name.replace(/^node:/,'')]));
 need(chunk.imports.every(name=>builtins.has(name))&&chunk.dynamicImports.length===0,'ObserverSdkBundleExternal');
 const inputs=[];
 for(const id of Object.keys(chunk.modules).sort()){
  if(id===RUNTIME_MODULE_ID)continue;
  const path=relative(root,id);need(!path.startsWith('/')&&!path.split('/').includes('..'),'ObserverSdkSourcePath');
  const bytes=await readFile(id),row={path,sha256:hash(bytes),bytesLength:bytes.length};
  if(path.startsWith('node_modules/')){
   const key=Object.keys(lock.packages).filter(key=>key.startsWith('node_modules/')&&path.startsWith(key+'/')).sort((a,b)=>b.length-a.length)[0];
   const pin=lock.packages[key];need(pin&&typeof pin.version==='string'&&typeof pin.integrity==='string','ObserverSdkPackageLock');
   row.packagePin={key,version:pin.version,integrity:pin.integrity};
  }
  inputs.push(row);
 }
 inputs.sort((a,b)=>a.path<b.path?-1:a.path>b.path?1:0);
 const bytes=Buffer.from(isolateObserverSdkCode(chunk.code)),manifest=Buffer.from(JSON.stringify({version:1,kind:'observer-sdk-codec-toolchain',nodeMajor:24,
  bundler:{name:'rolldown',version:VERSION,integrity:bundler.integrity,builderSourceHash:hash(await readFile(fileURLToPath(import.meta.url)))},
  packageLockHash:hash(lockBytes),entry,inputs,output:{path:outputPath,sha256:hash(bytes),bytesLength:bytes.length}},null,2)+'\n');
 need(bytes.length<=4*1024*1024&&manifest.length<=4*1024*1024,'ObserverSdkBundleBound');
 if(check)need((await readFile(join(root,outputPath))).equals(bytes)&&(await readFile(join(root,manifestPath))).equals(manifest),'ObserverSdkBundleStale');
 else{await writeFile(join(root,outputPath),bytes);await writeFile(join(root,manifestPath),manifest);}
 return {bundleHash:hash(bytes),bundleBytes:bytes.length,manifestHash:hash(manifest),inputs:inputs.length};
}

if(process.argv[1]===fileURLToPath(import.meta.url)){
 need(process.argv.length<=3&&(process.argv.length===2||process.argv[2]==='--check'),'ObserverSdkBuilderArguments');
 console.log(JSON.stringify(await buildObserverSdkCodec({check:process.argv[2]==='--check'})));
}
